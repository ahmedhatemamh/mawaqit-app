def moon(jde):
    """Geocentric ecliptic longitude and latitude (degrees) and distance (km) of the Moon."""
    T = _t(jde)
    Lp = 218.3164477 + 481267.88123421 * T - 0.0015786 * T * T
    D = 297.8501921 + 445267.1114034 * T - 0.0018819 * T * T
    M = 357.5291092 + 35999.0502909 * T - 0.0001536 * T * T
    Mp = 134.9633964 + 477198.8675055 * T + 0.0087414 * T * T
    F = 93.2720950 + 483202.0175233 * T - 0.0036539 * T * T
    A1 = 119.75 + 131.849 * T
    A2 = 53.09 + 479264.290 * T
    A3 = 313.45 + 481266.484 * T
    E = 1 - 0.002516 * T - 0.0000074 * T * T
    sl = sb = sr = 0.0
    for d, m, mp, f, c in _LON:
        arg = (d * D + m * M + mp * Mp + f * F) * D2R
        sl += c * (E ** abs(m)) * math.sin(arg)
    for d, m, mp, f, c in _LAT:
        arg = (d * D + m * M + mp * Mp + f * F) * D2R
        sb += c * (E ** abs(m)) * math.sin(arg)
    for d, m, mp, f, c in _DIST:
        arg = (d * D + m * M + mp * Mp + f * F) * D2R
        sr += c * (E ** abs(m)) * math.cos(arg)
    sl += 3958 * math.sin(A1 * D2R) + 1962 * math.sin((Lp - F) * D2R) + 318 * math.sin(A2 * D2R)
    sb += (-2235 * math.sin(Lp * D2R) + 382 * math.sin(A3 * D2R) + 175 * math.sin((A1 - F) * D2R)
           + 175 * math.sin((A1 + F) * D2R) + 127 * math.sin((Lp - Mp) * D2R) - 115 * math.sin((Lp + Mp) * D2R))
    lon = (Lp + sl / 1e6) % 360.0
    lat = sb / 1e6
    dist = 385000.56 + sr / 1000.0
    return lon, lat, dist


def nutation_and_obliquity(jde):
    T = _t(jde)
    omega = (125.04452 - 1934.136261 * T) * D2R
    Ls = (280.4665 + 36000.7698 * T) * D2R
    Lm = (218.3165 + 481267.8813 * T) * D2R
    dpsi = (-17.20 * math.sin(omega) - 1.32 * math.sin(2 * Ls) - 0.23 * math.sin(2 * Lm) + 0.21 * math.sin(2 * omega)) / 3600
    deps = (9.20 * math.cos(omega) + 0.57 * math.cos(2 * Ls) + 0.10 * math.cos(2 * Lm) - 0.09 * math.cos(2 * omega)) / 3600
    eps0 = 23.0 + 26.0 / 60 + 21.448 / 3600 - (46.8150 * T + 0.00059 * T * T - 0.001813 * T ** 3) / 3600
    return dpsi, eps0 + deps


def to_equatorial(lon, lat, eps):
    l, b, e = lon * D2R, lat * D2R, eps * D2R
    ra = math.atan2(math.sin(l) * math.cos(e) - math.tan(b) * math.sin(e), math.cos(l))
    dec = math.asin(math.sin(b) * math.cos(e) + math.cos(b) * math.sin(e) * math.sin(l))
    return ra % (2 * math.pi), dec


def gmst(jd_ut):
    T = (jd_ut - 2451545.0) / 36525.0
    g = 280.46061837 + 360.98564736629 * (jd_ut - 2451545.0) + 0.000387933 * T * T - T ** 3 / 38710000.0
    return (g % 360.0) * D2R
