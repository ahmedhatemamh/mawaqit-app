"""Low-precision Moon and Sun positions (Meeus, Astronomical Algorithms, ch. 25 and 47, truncated).

Accuracy is about 0.1 degree for the Moon, which is enough to decide crescent-visibility criteria
(thresholds are coarse); it is checked against known new-moon times in check_moon.py.
"""
import math

D2R = math.pi / 180.0


def _t(jde):
    return (jde - 2451545.0) / 36525.0


def sun_longitude(jde):
    """Apparent ecliptic longitude of the Sun in degrees (Meeus ch. 25, low accuracy), and distance in AU."""
    T = _t(jde)
    L0 = 280.46646 + 36000.76983 * T + 0.0003032 * T * T
    M = 357.52911 + 35999.05029 * T - 0.0001537 * T * T
    e = 0.016708634 - 0.000042037 * T
    Mr = M * D2R
    C = ((1.914602 - 0.004817 * T) * math.sin(Mr) + (0.019993 - 0.000101 * T) * math.sin(2 * Mr)
         + 0.000289 * math.sin(3 * Mr))
    true_long = L0 + C
    nu = Mr + C * D2R
    R = 1.000001018 * (1 - e * e) / (1 + e * math.cos(nu))
    omega = 125.04 - 1934.136 * T
    app = true_long - 0.00569 - 0.00478 * math.sin(omega * D2R)
    return app % 360.0, R


