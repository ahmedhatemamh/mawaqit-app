"""Generate the Kotlin engine's Hijri data from the research code, so nothing is transcribed by hand.

Usage: python3 gen_hijri_data.py <hijri.json from mawaqit-data> <out_main_dir> <out_test_resources_dir>

Writes:
  <out_main_dir>/MoonTables.kt            the truncated lunar series (from moon.py)
  <out_main_dir>/BundledHijriMonths.kt    the month starts known today (a snapshot of hijri.json)
  <out_test_resources_dir>/golden_moon.csv.gz     Moon positions computed by moon.py
  <out_test_resources_dir>/golden_hijri.csv.gz    estimated month starts computed by estimator.py
"""
import csv
import datetime as dt
import gzip
import io
import json
import math
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import crescent
import estimator
import moon

FIRST_YEAR_AH, LAST_YEAR_AH = 1300, 1600


def write_gz(path, header, rows):
    # mtime=0 keeps the output byte-identical between runs
    with open(path, "wb") as raw, gzip.GzipFile(fileobj=raw, mode="wb", mtime=0) as gz, \
            io.TextIOWrapper(gz, encoding="utf-8", newline="") as f:
        w = csv.writer(f, lineterminator="\n")
        w.writerow(header)
        for r in rows:
            w.writerow(r)


def flat(rows):
    return ", ".join(repr(float(x)) for row in rows for x in row)


def write_moon_tables(path):
    with open(path, "w", encoding="utf-8") as f:
        f.write("// GENERATED by research/hijri-estimate/gen_hijri_data.py from moon.py. Do not edit by hand.\n")
        f.write("// Truncated lunar series (Meeus, Astronomical Algorithms, ch. 47): flat (D, M, M', F, coefficient) tuples,\n")
        f.write("// coefficients in 1e-6 degrees (longitude, latitude) or 1e-3 km (distance).\n")
        f.write("package work.ahmedhatem.mawaqit.engine\n\ninternal object MoonTables {\n")
        f.write("    val LONGITUDE = doubleArrayOf(%s)\n" % flat(moon._LON))
        f.write("    val LATITUDE = doubleArrayOf(%s)\n" % flat(moon._LAT))
        f.write("    val DISTANCE = doubleArrayOf(%s)\n" % flat(moon._DIST))
        f.write("}\n")


def write_bundled(path, state):
    months = sorted(state["months"], key=lambda m: (m["year"], m["month"]))
    with open(path, "w", encoding="utf-8") as f:
        f.write("// GENERATED by research/hijri-estimate/gen_hijri_data.py from docs/hijri.json of mawaqit-data. Do not edit by hand.\n")
        f.write("// Snapshot of the official month starts (Dar al-Ifta) up to %d-%02d. Regenerate before a release.\n"
                % (months[-1]["year"], months[-1]["month"]))
        f.write("package work.ahmedhatem.mawaqit.engine\n\nimport java.time.LocalDate\n\ninternal object BundledHijriMonths {\n")
        f.write("    val all: List<HijriMonthStart> = listOf(\n")
        for m in months:
            y, mo, d = m["start"].split("-")
            f.write("        HijriMonthStart(%d, %d, LocalDate.of(%s, %s, %s)),\n" % (m["year"], m["month"], int(y), int(mo), int(d)))
        f.write("    )\n}\n")
    return months


def moon_rows():
    rows = []
    for i in range(400):
        jde = 2415020.5 + i * 191.37  # 1900 to 2100
        lon, lat, dist = moon.moon(jde)
        rows.append([repr(jde), "%.9f" % lon, "%.9f" % lat, "%.6f" % dist])
    return rows


def hijri_rows(months):
    anchor = months[-1]
    anchor_index = anchor["year"] * 12 + anchor["month"] - 1
    anchor_start = dt.date.fromisoformat(anchor["start"])
    k0 = estimator.lunation_of_start(anchor_start)
    rows = []
    for year in range(FIRST_YEAR_AH, LAST_YEAR_AH + 1):
        for month in range(1, 13):
            idx = year * 12 + month - 1
            k = k0 + (idx - anchor_index)
            start, margin = estimator.estimated_start_and_margin(k)
            rows.append([k, start.isoformat(), "%.6f" % margin])
    return k0, rows


def main():
    hijri_json, out_main, out_res = sys.argv[1:4]
    state = json.load(open(hijri_json, encoding="utf-8"))
    os.makedirs(out_main, exist_ok=True)
    os.makedirs(out_res, exist_ok=True)
    write_moon_tables(os.path.join(out_main, "MoonTables.kt"))
    months = write_bundled(os.path.join(out_main, "BundledHijriMonths.kt"), state)
    write_gz(os.path.join(out_res, "golden_moon.csv.gz"), ["jde", "lon", "lat", "dist"], moon_rows())
    k0, rows = hijri_rows(months)
    write_gz(os.path.join(out_res, "golden_hijri.csv.gz"), ["lunation", "start", "margin"], rows)
    print("months", len(months), "| anchor lunation", k0, "| golden months", len(rows))


if __name__ == "__main__":
    main()
