def _s(terms, t):
    return sum(a * math.cos(b + c * t) for a, b, c in terms)

def sun_vsop(jd, delta_t_s=69.0):
    jde = jd + delta_t_s / 86400
    tau = (jde - 2451545.0) / 365250.0
    T = tau * 10
    L = (_s(L0, tau) + _s(L1, tau) * tau + _s(L2, tau) * tau**2 + _s(L3, tau) * tau**3
         + _s(L4, tau) * tau**4 + _s(L5, tau) * tau**5) / 1e8
    B = (_s(B0, tau) + _s(B1, tau) * tau) / 1e8
    R = (_s(R0, tau) + _s(R1, tau) * tau + _s(R2, tau) * tau**2) / 1e8
    lam = math.degrees(L) + 180.0
    beta = -math.degrees(B)
    # FK5 correction
    lp = math.radians(lam - 1.397 * T - 0.00031 * T * T)
    lam += -0.09033 / 3600
    beta += 0.03916 / 3600 * (math.cos(lp) - math.sin(lp))
    # nutation (Meeus 22, low order) and obliquity
    omega = math.radians(125.04452 - 1934.136261 * T)
    Ls = math.radians(280.4665 + 36000.7698 * T); Lm = math.radians(218.3165 + 481267.8813 * T)
    dpsi = (-17.20 * math.sin(omega) - 1.32 * math.sin(2 * Ls) - 0.23 * math.sin(2 * Lm) + 0.21 * math.sin(2 * omega)) / 3600
    deps = (9.20 * math.cos(omega) + 0.57 * math.cos(2 * Ls) + 0.10 * math.cos(2 * Lm) - 0.09 * math.cos(2 * omega)) / 3600
    U = T / 100
    eps0 = 23 + 26 / 60 + 21.448 / 3600 + (-4680.93 * U - 1.55 * U**2 + 1999.25 * U**3 - 51.38 * U**4
            - 249.67 * U**5 - 39.05 * U**6 + 7.12 * U**7 + 27.87 * U**8 + 5.79 * U**9 + 2.45 * U**10) / 3600
    eps = math.radians(eps0 + deps)
    lam_app = math.radians(lam + dpsi - 20.4898 / 3600 / R)
    b = math.radians(beta)
    ra = math.degrees(math.atan2(math.sin(lam_app) * math.cos(eps) - math.tan(b) * math.sin(eps), math.cos(lam_app))) % 360
    dec = math.asin(math.sin(b) * math.cos(eps) + math.cos(b) * math.sin(eps) * math.sin(lam_app))
    L0m = (280.4664567 + 360007.6982779 * tau + 0.03032028 * tau**2 + tau**3 / 49931 - tau**4 / 15300 - tau**5 / 2000000) % 360
    E = L0m - 0.0057183 - ra + dpsi * math.cos(eps)
    E = (E + 180) % 360 - 180
    return dec, 4 * E
