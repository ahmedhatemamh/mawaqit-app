"""Generate the Kotlin engine's data from the research code, so nothing is transcribed by hand.

Usage: python3 gen_engine_data.py <coords.json from fit_all2.py> <out_main_dir> <out_test_resources_dir>

Writes:
  <out_main_dir>/Vsop87Tables.kt   the abridged VSOP87 series (from vsop.py)
  <out_main_dir>/Cities.kt         city names and fitted coordinates (6 decimals)
  <out_test_resources_dir>/golden_times.csv.gz   reference answers computed by the research code
The golden file holds only our own computed values, never data published by the Survey Authority.
"""
import csv
import datetime as dt
import gzip
import io
import json
import math
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import solar
import vsop

DELTA_T = 69.0
KW = dict(rise=0.845, asr_noon=True, dst_mode="eqt_all")
DECIMALS = 6
SAMPLE_CITIES = ["القاهرة", "الأسكندرية", "أسوان", "مطروح", "شرم الشيخ", "العريش"]
SAMPLE_YEARS = [1950, 1990, 2000, 2014, 2015, 2016, 2022, 2023, 2024, 2025, 2027, 2030, 2050, 2100]


def norm(s):
    return " ".join(s.replace("ـ", "").split())


def kotlin_array(name, terms):
    flat = ", ".join(repr(float(x)) for t in terms for x in t)
    return "    val %s = doubleArrayOf(%s)\n" % (name, flat)


def write_vsop(path):
    names = ["L0", "L1", "L2", "L3", "L4", "L5", "B0", "B1", "R0", "R1", "R2"]
    with open(path, "w", encoding="utf-8") as f:
        f.write("// GENERATED by research/esa-formula/scripts/gen_engine_data.py from vsop.py. Do not edit by hand.\n")
        f.write("// Abridged VSOP87 Earth series (Meeus, Astronomical Algorithms, ch. 32): flat (amplitude, phase, frequency) triples.\n")
        f.write("package work.ahmedhatem.mawaqit.engine\n\ninternal object Vsop87Tables {\n")
        for n in names:
            f.write(kotlin_array(n, getattr(vsop, n)))
        f.write("}\n")


def write_cities(path, cities):
    with open(path, "w", encoding="utf-8") as f:
        f.write("// GENERATED by research/esa-formula/scripts/gen_engine_data.py from the coordinate fit. Do not edit by hand.\n")
        f.write("// Coordinates are inferred from our analysis of the published tables, rounded to %d decimals.\n" % DECIMALS)
        f.write("package work.ahmedhatem.mawaqit.engine\n\nobject Cities {\n    val all: List<City> = listOf(\n")
        for name, lat, lon in cities:
            f.write('        City("%s", %s, %s),\n' % (name, repr(round(lat, DECIMALS)), repr(round(lon, DECIMALS))))
        f.write("    )\n}\n")


def rule_offset(date):
    """The app's summer-time rule, written independently of the Kotlin code (see EgyptDst.kt).

    2015-2022: none. 2023 onward: UTC+3 from the last Friday of April to the last Thursday of October, inclusive.
    Years outside 2015-2026 use the rule of the nearest of those years.
    """
    rule_year = min(max(date.year, 2015), 2026)
    if rule_year < 2023:
        return 2
    def last(month, weekday):
        d = dt.date(date.year, month + 1, 1) - dt.timedelta(days=1)
        while d.weekday() != weekday:
            d -= dt.timedelta(days=1)
        return d
    return 3 if last(4, 4) <= date <= last(10, 3) else 2


def python_times(date, lat, lon):
    solar.sun = lambda jd: vsop.sun_vsop(jd, DELTA_T)
    t = solar.times(date, lat, lon, tz=rule_offset(date), **KW)
    return t, [math.floor(x + 0.5) for x in t]


def write_golden(path, cities):
    by_name = {n: (la, lo) for n, la, lo in cities}
    rows = []
    d = dt.date(2026, 1, 1)
    while d.year == 2026:
        for name, lat, lon in cities:
            rows.append((lat, lon, d))
        d += dt.timedelta(days=1)
    for name in SAMPLE_CITIES:
        lat, lon = by_name[norm(name)]
        for y in SAMPLE_YEARS:
            for m in range(1, 13):
                for day in (1, 15):
                    rows.append((lat, lon, dt.date(y, m, day)))
    # mtime=0 keeps the output byte-identical between runs
    with open(path, "wb") as raw, gzip.GzipFile(fileobj=raw, mode="wb", mtime=0) as gz, \
            io.TextIOWrapper(gz, encoding="utf-8", newline="") as f:
        w = csv.writer(f, lineterminator="\n")
        w.writerow(["lat", "lon", "date", "exact_fajr", "exact_sunrise", "exact_dhuhr", "exact_asr", "exact_maghrib",
                    "exact_isha", "min_fajr", "min_sunrise", "min_dhuhr", "min_asr", "min_maghrib", "min_isha"])
        for lat, lon, d in rows:
            exact, mins = python_times(d, lat, lon)
            w.writerow([repr(lat), repr(lon), d.isoformat()] + ["%.6f" % x for x in exact] + mins)
    return len(rows)


def main():
    coords, out_main, out_res = sys.argv[1:4]
    raw = json.load(open(coords, encoding="utf-8"))
    cities = sorted(((norm(r[0]), round(r[1], DECIMALS), round(r[2], DECIMALS)) for r in raw), key=lambda c: c[0])
    if len(cities) != 78 or len({c[0] for c in cities}) != 78:
        raise SystemExit("input error: expected 78 distinct cities, got %d" % len(cities))
    os.makedirs(out_main, exist_ok=True)
    os.makedirs(out_res, exist_ok=True)
    write_vsop(os.path.join(out_main, "Vsop87Tables.kt"))
    write_cities(os.path.join(out_main, "Cities.kt"), cities)
    n = write_golden(os.path.join(out_res, "golden_times.csv.gz"), cities)
    print("cities", len(cities), "golden rows", n)


if __name__ == "__main__":
    main()
